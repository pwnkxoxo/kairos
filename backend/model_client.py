# 5. Safe Output Parsing & Validation
# ------------------------------------------------------------------------------
def parse_and_validate_model_output(raw_text: str, model_name: str) -> GemmaPlan:
    """
    Parses and strictly validates the JSON response from Gemma.
    Rejects malformed, missing, oversized, or incorrectly typed values.
    """
    if not raw_text or not raw_text.strip():
        raise ModelClientError("Model returned an empty response.")

    cleaned = raw_text.strip()
    # Remove markdown code block fences if present
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
        cleaned = re.sub(r"\s*```$", "", cleaned)
        cleaned = cleaned.strip()

    try:
        parsed_json = json.loads(cleaned, strict=False)
    except json.JSONDecodeError:
        # Fallback: Fix invalid single backslashes in math formulas (e.g. \frac, \int, \alpha)
        # that are valid LaTeX but invalid JSON string escape sequences
        try:
            fixed_escapes = re.sub(r'\\(?![/"\\bfnrtu])', r'\\\\', cleaned)
            parsed_json = json.loads(fixed_escapes, strict=False)
        except json.JSONDecodeError as e:
            raise ModelClientError(f"Model returned invalid JSON: {str(e)[:100]}")

    if not isinstance(parsed_json, dict):
        raise ModelClientError("Model output is not a JSON object.")

    # Strictly validate fields via Pydantic
    try:
        validated = GemmaRawOutput(**parsed_json)
    except ValidationError as e:
        raise ModelClientError(f"Model output schema validation failed: {str(e)[:200]}")

    # Enforce content length ceiling
    if len(validated.file_content) > MAX_CONTENT_LENGTH:
        raise ModelClientError(
            f"Model generated content exceeds maximum allowed length of {MAX_CONTENT_LENGTH} characters."
        )

    # For supported requests, ensure required content and description are populated
    target_file = None
    if validated.supported:
        if not validated.file_content.strip():
            raise ModelClientError("Supported request produced empty file content.")
        raw_target = (validated.target_file or "").strip()
        if raw_target:
            from backend.agent import validate_and_resolve_target_path
            try:
                # Server-side validation: must resolve safely within workspace
                validate_and_resolve_target_path(raw_target)
                target_file = raw_target
            except (ValueError, PermissionError) as e:
                raise ModelClientError(f"Model proposed an invalid or unsafe target path: {e}")
        else:
            target_file = "demo.txt"

        if not validated.plan_description.strip():
            validated.plan_description = f"Create '{target_file}' inside workspace/ with the generated content."
    else:
        # Clear out any executable content on unsupported requests
        validated.file_content = ""
        validated.plan_description = ""
        target_file = None

    # Validate intent against strict allow-list
    inferred_intent = validated.intent or ("create_file" if validated.supported else "unsupported")
    if inferred_intent not in VALID_INTENTS:
        inferred_intent = "create_file" if validated.supported else "unsupported"

    # Supported requests must have intent 'create_file'
    if validated.supported and inferred_intent != "create_file":
        inferred_intent = "create_file"

    return GemmaPlan(
        supported=validated.supported,
        assistant_message=validated.assistant_message.strip(),
        plan_description=validated.plan_description.strip(),
        file_content=validated.file_content,
        intent=inferred_intent,
        mode="gemma",
        model_name=model_name,
        target_file=target_file,
    )


