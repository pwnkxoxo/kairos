# ------------------------------------------------------------------------------
# 3. Provider-Independent Abstraction Interface
# ------------------------------------------------------------------------------
@dataclass
class ModelRequest:
    """Provider-independent model execution request."""
    prompt: str
    system_instruction: Optional[str] = None
    timeout_ms: Optional[int] = None
    retry_attempts: Optional[int] = 2
    metadata: Optional[Dict[str, Any]] = None


@dataclass
class ModelResponse:
    """Provider-independent model execution response."""
    text: str
    model_name: str
    provider_name: str = "gemma"
    metadata: Optional[Dict[str, Any]] = None


class BaseModelProvider:
    """Abstract base class for AI model providers."""

    def is_available(self) -> bool:
        """Returns True if this provider is configured and available."""
        raise NotImplementedError

    def get_model_name(self) -> str:
        """Returns the active model identifier."""
        raise NotImplementedError

    def generate(self, request: ModelRequest) -> ModelResponse:
        """Executes a model generation request and returns ModelResponse."""
        raise NotImplementedError


class GemmaProvider(BaseModelProvider):
    """
    Google Gen AI / Gemma 4 implementation of BaseModelProvider.
    Encapsulates client initialization, timeout configuration, and bounded retries.
    """

    def __init__(self, client: Optional[Any] = None):
        self._client = client

    def is_available(self) -> bool:
        return is_gemini_configured()

    def get_model_name(self) -> str:
        return get_model_name()

    def get_client(self, timeout_ms: Optional[int] = None, retry_attempts: Optional[int] = 2) -> Any:
        if self._client is not None:
            return self._client

        api_key = get_api_key()
        if not api_key:
            raise ModelClientError("GEMINI_API_KEY is not configured.")

        try:
            from google import genai
            from google.genai import types

            eff_timeout = timeout_ms or get_model_timeout_ms()
            attempts = retry_attempts if retry_attempts is not None else 2
            return genai.Client(
                api_key=api_key,
                http_options=types.HttpOptions(
                    timeout=eff_timeout,
                    retry_options=types.HttpRetryOptions(attempts=attempts),
                ),
            )
        except Exception as e:
            raise ModelClientError(sanitize_provider_error(e))

    def generate(self, request: ModelRequest) -> ModelResponse:
        client = self.get_client(timeout_ms=request.timeout_ms, retry_attempts=request.retry_attempts)
        model = self.get_model_name()

        try:
            response = client.models.generate_content(
                model=model,
                contents=request.prompt,
            )
        except Exception as e:
            raise ModelClientError(sanitize_provider_error(e))

        if not response or not hasattr(response, "text") or not response.text:
            raise ModelClientError("Model returned an empty response.")

        return ModelResponse(
            text=response.text.strip(),
            model_name=model,
            provider_name="gemma",
        )


# Singleton provider instance
_active_provider: BaseModelProvider = GemmaProvider()


def get_active_provider() -> BaseModelProvider:
    """Returns the current active model provider (Gemma)."""
    return _active_provider


