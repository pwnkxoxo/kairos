# 8. Gemma PDF Content Analyser
# ------------------------------------------------------------------------------
def analyze_pdf_content(
    document_context: str,
    user_question: str,
    truncated: bool = False,
    client: Optional[Any] = None,
    provider: Optional[BaseModelProvider] = None,
) -> str:
    """
    Submits extracted document text and user question to hosted Gemma for read-only analysis.
    Uses bounded retries for transient provider errors (500, 503).
    Does not loop retries on request timeouts.
    Never fabricates an answer on failure.
    """
    active_prov = provider or (GemmaProvider(client=client) if client is not None else get_active_provider())

    if not active_prov.is_available() and client is None:
        raise ModelClientError("GEMINI_API_KEY is not configured. PDF analysis requires an active API key.")

    truncation_notice = ""
    if truncated:
        truncation_notice = (
            "\n[Note: This document was long and only the first portion could be included in the context window.]\n"
        )

    prompt = PDF_ANALYSIS_PROMPT_TEMPLATE.format(
        document_context=document_context,
        truncation_notice=truncation_notice,
        user_question=user_question.strip(),
    )

    request = ModelRequest(
        prompt=prompt,
        timeout_ms=get_model_timeout_ms(),
        retry_attempts=1,
    )

    # Bounded retries: up to 2 attempts only for transient server errors (not timeouts)
    max_attempts = 2
    last_err: Optional[Exception] = None

    for attempt in range(max_attempts):
        try:
            response = active_prov.generate(request)
            return response.text.strip()
        except Exception as exc:
            last_err = exc
            err_lower = str(exc).lower()
            # If it's a timeout, do not retry repeatedly to avoid compounding wait time
            is_timeout = any(k in err_lower for k in ["timeout", "timed out", "deadline"])
            if is_timeout:
                raise ModelClientError(sanitize_provider_error(exc))

            is_transient = any(
                k in err_lower
                for k in ["500", "internal", "503", "unavailable", "temporarily"]
            )
            if is_transient and attempt < max_attempts - 1:
                time.sleep(1.0)
                continue
            raise ModelClientError(sanitize_provider_error(exc))

    raise ModelClientError(sanitize_provider_error(last_err or Exception("Unknown model error")))

