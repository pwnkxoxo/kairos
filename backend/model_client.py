def format_context_slice(
    context_slice: Optional[List[Dict[str, str]]],
    max_turn_chars: int = 1200,
) -> str:
    """
    Formats recent conversation turns into a bounded context section.
    Preserves recent context turns in chronological order.
    For individual past messages exceeding max_turn_chars, retains both the beginning
    (context/instructions) and the end (latest constraints/decisions/files) with a clear omission marker,
    preventing context pollution while avoiding loss of critical detail.
    """
    if not context_slice:
        return ""

    formatted_slice = []
    for msg in context_slice:
        role_label = "User" if msg.get("role") == "user" else "Assistant"
        raw_content = msg.get("content", "").strip()
        if len(raw_content) > max_turn_chars:
            head_len = max_turn_chars // 2
            tail_len = max_turn_chars - head_len
            raw_content = (
                raw_content[:head_len].rstrip()
                + "\n... [middle content omitted for brevity] ...\n"
                + raw_content[-tail_len:].lstrip()
            )
        formatted_slice.append(f"{role_label}: {raw_content}")

    return (
        "--- Recent Conversation History ---\n"
        + "\n".join(formatted_slice)
        + "\n-----------------------------------\n"
    )


