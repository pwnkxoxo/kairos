DEFAULT_MODEL = "gemma-4-26b-a4b-it"
MAX_CONTENT_LENGTH = 10000


def get_api_key() -> Optional[str]:
    """Retrieve GEMINI_API_KEY from environment. Returns None if unconfigured or placeholder."""
    key = os.getenv("GEMINI_API_KEY", "").strip()
    if not key or key == "your_gemini_api_key_here":
        return None
    return key


def is_gemini_configured() -> bool:
    """Return True if a valid-looking API key is present."""
    return get_api_key() is not None


def get_model_name() -> str:
    """Retrieve model name from environment, defaulting to gemma-4-26b-a4b-it."""
    return os.getenv("GEMMA_MODEL", DEFAULT_MODEL).strip() or DEFAULT_MODEL


DEFAULT_MODEL_TIMEOUT_MS = 60000


def get_model_timeout_ms() -> int:
    """
    Returns the Google Gen AI request timeout in milliseconds.
    Configurable via GEMINI_REQUEST_TIMEOUT_MS env var (default: 60,000 ms = 60 seconds).
    """
    raw = os.getenv("GEMINI_REQUEST_TIMEOUT_MS", "").strip()
    if raw:
        try:
            val = int(raw)
            if val > 0:
                return val
        except ValueError:
            pass
    return DEFAULT_MODEL_TIMEOUT_MS


