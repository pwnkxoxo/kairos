# 6. Error Sanitization
# ------------------------------------------------------------------------------
def sanitize_provider_error(err: Exception) -> str:
    """
    Sanitizes provider errors to ensure no API keys, auth headers,
    or internal secrets are ever leaked in error messages.
    """
    err_str = str(err)
    key = get_api_key()
    if key and key in err_str:
        err_str = err_str.replace(key, "[REDACTED]")

    lower = err_str.lower()
    if any(k in lower for k in ["401", "api_key", "invalid api key", "unauthenticated"]):
        return "Authentication failed with Google AI service. Please verify your GEMINI_API_KEY."
    if any(k in lower for k in ["429", "quota", "resource_exhausted"]):
        return "Google AI rate limit or quota exceeded. Please try again later."
    if any(k in lower for k in ["timeout", "timed out", "deadline"]):
        return "Google AI service request timed out."
    if any(k in lower for k in ["name resolution", "temporary failure in name resolution", "nodename nor servname", "failed to resolve", "connection error", "connection refused", "network unreachable", "dns", "errno -3"]):
        return "Unable to reach Google AI service due to network or DNS resolution failure. Please check network connectivity."
    if any(k in lower for k in ["503", "unavailable"]):
        return "Google AI service is currently unavailable. Please try again later."
    if any(k in lower for k in ["500", "internal"]):
        return "Google AI service encountered an internal error. Please try again."

    return f"AI service error: {err_str[:200]}"


